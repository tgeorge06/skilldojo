#!/usr/bin/env node

// Generate one small, versioned Opus clip for each unique curriculum word.
// This is a development task; the browser only downloads normal audio files.
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const vm = require("node:vm");

const root = path.join(__dirname, "..");
const args = process.argv.slice(2);

function option(name, fallback) {
  const index = args.indexOf(name);
  return index === -1 ? fallback : args[index + 1];
}

const voice = option("--voice", "Samantha");
const rate = option("--rate", "155");
const version = option("--version", "samantha-v1");
const force = args.includes("--force");
const wordsFile = path.join(root, "static", "words.js");
const audioRoot = path.join(root, "static", "audio", "spelling");
const outputDir = path.join(audioRoot, version);
const manifestFile = path.join(audioRoot, "manifest.js");

if (process.platform !== "darwin") {
  throw new Error("Audio generation currently requires macOS and its `say` command.");
}
execFileSync("ffmpeg", ["-version"], { stdio: "ignore" });
const voices = execFileSync("say", ["-v", "?"], { encoding: "utf8" });
if (!voices.split("\n").some((line) => line.startsWith(`${voice} `))) {
  throw new Error(`The macOS voice ${JSON.stringify(voice)} is not installed.`);
}

const context = vm.createContext({});
vm.runInContext(fs.readFileSync(wordsFile, "utf8"), context, { filename: wordsFile });
const spellingWords = vm.runInContext("SPELLING_WORDS", context);
const sightWords = vm.runInContext("SIGHT_WORDS", context);
const words = [...new Set(
  [...Object.values(spellingWords).flat(), ...Object.values(sightWords).flat()]
    .map(({ word }) => word)
)].sort();

if (words.some((word) => !/^[a-z]+$/.test(word))) {
  throw new Error("Audio filenames require lowercase a-z curriculum words.");
}

fs.mkdirSync(outputDir, { recursive: true });
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "skilldojo-audio-"));
let generated = 0;

try {
  words.forEach((word, index) => {
    const output = path.join(outputDir, `${word}.opus`);
    if (!force && fs.existsSync(output) && fs.statSync(output).size > 0) return;

    const source = path.join(tempDir, `${word}.aiff`);
    execFileSync("say", ["-v", voice, "-r", rate, "-o", source, `${word}.`]);
    execFileSync("ffmpeg", [
      "-hide_banner", "-loglevel", "error", "-y", "-i", source,
      "-af", "loudnorm=I=-18:TP=-2:LRA=7",
      "-ac", "1", "-c:a", "libopus", "-b:a", "32k", "-vbr", "on", output,
    ]);
    fs.unlinkSync(source);
    generated += 1;
    if ((index + 1) % 20 === 0 || index + 1 === words.length) {
      process.stdout.write(`Prepared ${index + 1}/${words.length} words\n`);
    }
  });
} finally {
  fs.rmSync(tempDir, { recursive: true, force: true });
}

const manifest = {
  basePath: `/static/audio/spelling/${version}`,
  format: "opus",
  voice,
  words,
};
fs.writeFileSync(
  manifestFile,
  `// Generated by scripts/generate-spelling-audio.js.\nconst SPELLING_AUDIO = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`,
);
process.stdout.write(`${generated ? `Generated ${generated}` : "Kept"} clips in ${path.relative(root, outputDir)}.\n`);
